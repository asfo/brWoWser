static WardenInteger warden_integer(const uint8_t *bytes) {
  WardenInteger value;
  for (uint32_t i = 0; i < 64; i++)
    value.limb[i] = warden_read32(bytes + i * 4);
  return value;
}
static int warden_compare(const WardenInteger *a, const WardenInteger *b) {
  for (uint32_t i = 64; i > 0; i--) {
    if (a->limb[i - 1] != b->limb[i - 1])
      return a->limb[i - 1] > b->limb[i - 1] ? 1 : -1;
  }
  return 0;
}
static WardenInteger warden_addmod(WardenInteger a, const WardenInteger *b,
                                   const WardenInteger *modulus) {
  uint64_t carry = 0;
  for (uint32_t i = 0; i < 64; i++) {
    uint64_t sum = (uint64_t)a.limb[i] + b->limb[i] + carry;
    a.limb[i] = (uint32_t)sum;
    carry = sum >> 32;
  }
  if (carry || warden_compare(&a, modulus) >= 0) {
    uint64_t borrow = 0;
    for (uint32_t i = 0; i < 64; i++) {
      uint32_t old = a.limb[i];
      uint64_t sub = (uint64_t)modulus->limb[i] + borrow;
      a.limb[i] = (uint32_t)((uint64_t)old - sub);
      borrow = (uint64_t)old < sub;
    }
  }
  return a;
}
static WardenInteger warden_multiply(WardenInteger a, const WardenInteger *b,
                                     const WardenInteger *modulus) {
  WardenInteger result = {{0}};
  for (uint32_t i = 0; i < 2048; i++) {
    if ((b->limb[i / 32] >> (i % 32)) & 1)
      result = warden_addmod(result, &a, modulus);
    a = warden_addmod(a, &a, modulus);
  }
  return result;
}
/* Container is mutable scratch storage. The digest suffix replaces NGIS only
 * after the signature has been copied; the compressed body is unchanged. */
static int warden_signature(uint8_t *container, uint32_t length) {
  if (length < 269 || memcmp(container + length - 260, "NGIS", 4))
    return 0;
  WardenInteger modulus = warden_integer(warden_signing_key);
  WardenInteger signature = warden_integer(container + length - 256);
  if (warden_compare(&signature, &modulus) >= 0)
    return 0;
  WardenInteger recovered = signature;
  for (uint32_t i = 0; i < 16; i++)
    recovered = warden_multiply(recovered, &recovered, &modulus);
  recovered = warden_multiply(recovered, &signature, &modulus);
  uint8_t digest[20];
  memcpy(container + length - 260, "MAIEV.MOD", 9);
  hash(container, length - 251, digest);
  erase(container + length - 260, 9);
  uint32_t difference = 0;
  for (uint32_t i = 0; i < 256; i++) {
    uint8_t actual = (uint8_t)(recovered.limb[i / 4] >> (8 * (i % 4)));
    uint8_t expected = i < 20 ? digest[i] : i == 255 ? 0x0b : 0xbb;
    difference |= actual ^ expected;
  }
  erase(&signature, sizeof(signature));
  erase(&recovered, sizeof(recovered));
  erase(digest, sizeof(digest));
  return difference == 0;
}
